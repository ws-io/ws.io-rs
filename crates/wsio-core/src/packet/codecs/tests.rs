/// Codec, packet-type byte index, `[Event, "e", null]` wire bytes, and `[Event, "e", empty bytes]` wire bytes.
fn fixtures() -> Vec<(WsIoPacketCodec, usize, &'static [u8], &'static [u8])> {
    vec![
        (
            WsIoPacketCodec::Msgpack,
            1,
            &[0x93, 1, 0xa1, b'e', 0xc0],
            &[0x93, 1, 0xa1, b'e', 0xc4, 0],
        ),
        #[cfg(feature = "packet-codec-cbor")]
        (
            WsIoPacketCodec::Cbor,
            1,
            &[0x83, 1, 0x61, b'e', 0xf6],
            &[0x83, 1, 0x61, b'e', 0x40],
        ),
        #[cfg(feature = "packet-codec-postcard")]
        (
            WsIoPacketCodec::Postcard,
            0,
            &[1, 1, 1, b'e', 0],
            &[1, 1, 1, b'e', 1, 0],
        ),
    ]
}

#[test]
fn wire_fixtures_distinguish_absent_and_empty_payload() {
    for (codec, _, absent, empty) in fixtures() {
        for (wire, data) in [(absent, None), (empty, Some(Bytes::new()))] {
            let packet = codec.decode(wire).unwrap();
            assert!(matches!(packet.r#type, WsIoPacketType::Event));
            assert_eq!(packet.key.as_deref(), Some("e"));
            assert_eq!(packet.data, data);
            assert_eq!(codec.encode(&WsIoPacket::new_event("e", data)).unwrap().as_ref(), wire);
        }
    }
}

#[test]
fn packets_and_typed_payload_round_trip_for_every_codec() {
    for (codec, _, _, _) in fixtures() {
        let payload = ("世界", vec![0_u32, 127, 128, u32::MAX]);
        let data = codec.encode_data(&payload).unwrap();
        assert_eq!(
            codec.decode_data::<(String, Vec<u32>)>(&data).unwrap(),
            (payload.0.to_owned(), payload.1)
        );

        for packet in [
            WsIoPacket::new_disconnect(),
            WsIoPacket::new_ready(),
            WsIoPacket::new_init(Some(data.clone())),
            WsIoPacket::new_event("世界", Some(data)),
        ] {
            let decoded = codec.decode(&codec.encode(&packet).unwrap()).unwrap();
            assert_eq!(decoded.r#type as u8, packet.r#type as u8);
            assert_eq!(decoded.key, packet.key);
            assert_eq!(decoded.data, packet.data);
        }

        // An independent scalar fixture, not generated by the encoder under test.
        assert_eq!(codec.encode_data(&7_u8).unwrap().as_ref(), &[7]);
        assert_eq!(codec.decode_data::<u8>(&[7]).unwrap(), 7);
    }
}

#[test]
fn malformed_packets_and_every_truncated_fixture_are_rejected() {
    for (codec, type_index, absent, empty) in fixtures() {
        for fixture in [absent, empty] {
            for end in 0..fixture.len() {
                assert!(codec.decode(&fixture[..end]).is_err(), "{codec:?}, prefix {end}");
            }
        }

        assert!(codec.decode(&[0xff]).is_err());
        assert!(codec.decode_data::<u64>(&[]).is_err());
        let payload = codec.encode_data(&"payload").unwrap();
        for end in 0..payload.len() {
            assert!(codec.decode_data::<String>(&payload[..end]).is_err());
        }

        for key in [None, Some("")] {
            let invalid = WsIoPacket::new(WsIoPacketType::Event, key, None);
            assert!(codec.decode(&codec.encode(&invalid).unwrap()).is_err());
        }

        let mut invalid_type = absent.to_vec();
        invalid_type[type_index] = 7;
        assert!(codec.decode(&invalid_type).is_err());
    }
}

struct ScalarCustomCodec {
    fail: bool,
}

impl WsIoPacketCustomCodec for ScalarCustomCodec {
    fn decode(&self, bytes: &[u8]) -> Result<WsIoPacket> {
        ensure!(!self.fail, "custom decode failure");
        WsIoPacketCodec::Msgpack.decode(bytes)
    }

    fn encode(&self, packet: &WsIoPacket) -> Result<Bytes> {
        ensure!(!self.fail, "custom encode failure");
        WsIoPacketCodec::Msgpack.encode(packet)
    }

    fn decode_data<'de>(&self, bytes: &'de [u8]) -> Result<Box<dyn ErasedDeserializer<'de> + 'de>> {
        ensure!(!self.fail, "custom payload decode failure");
        ensure!(bytes.len() == 1, "expected a scalar byte");
        let decoder = U8Deserializer::<ValueError>::new(bytes[0]);
        Ok(Box::new(<dyn ErasedDeserializer>::erase(decoder)))
    }

    fn encode_data(&self, data: &dyn ErasedSerialize) -> Result<Bytes> {
        ensure!(!self.fail, "custom payload encode failure");
        Ok(to_vec_named(data)?.into())
    }
}

#[test]
fn custom_codec_delegates_erased_payloads_and_preserves_errors() {
    let codec = WsIoPacketCodec::Custom(Arc::new(ScalarCustomCodec { fail: false }));
    let packet = WsIoPacket::new_event("e", Some(codec.encode_data(&7_u8).unwrap()));
    let decoded = codec.decode(&codec.encode(&packet).unwrap()).unwrap();
    assert_eq!(decoded.key, packet.key);
    assert_eq!(codec.decode_data::<u8>(&decoded.data.unwrap()).unwrap(), 7);
    assert!(codec.decode_data::<String>(&[7]).is_err());
    let codec = WsIoPacketCodec::Custom(Arc::new(ScalarCustomCodec { fail: true }));
    assert_eq!(codec.encode(&packet).unwrap_err().to_string(), "custom encode failure");
    assert_eq!(codec.decode(&[]).unwrap_err().to_string(), "custom decode failure");
    assert_eq!(
        codec.encode_data(&7_u8).unwrap_err().to_string(),
        "custom payload encode failure"
    );

    assert_eq!(
        codec.decode_data::<u8>(&[7]).unwrap_err().to_string(),
        "custom payload decode failure"
    );
}
